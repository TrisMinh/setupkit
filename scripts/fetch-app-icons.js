const outputDirectory = path.join(__dirname, '..', 'assets', 'apps');

async function download(url) {
  const response = await fetch(url, {
    headers: { 'User-Agent': 'SetupKit icon asset fetcher' }
  });
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

async function main() {
  fs.mkdirSync(outputDirectory, { recursive: true });

  let saved = 0;
  let skipped = 0;
  const entries = Object.entries(simpleIcons);
  for (let index = 0; index < entries.length; index += 12) {
    const batch = entries.slice(index, index + 12);
    await Promise.all(batch.map(async ([id, icon]) => {
      const url = `https://cdn.jsdelivr.net/npm/simple-icons@latest/icons/${icon.slug}.svg`;
      try {
        const buffer = await download(url);
        const svg = buffer.toString('utf8').replace('<svg ', `<svg fill="#${icon.color}" `);
        fs.writeFileSync(path.join(outputDirectory, `${id}.svg`), svg);
        saved += 1;
        process.stdout.write(`saved ${id}.svg\n`);
      } catch (error) {
        skipped += 1;
        process.stderr.write(`skipped ${id}: ${error.message}\n`);
      }
    }));
  }

  for (const [id, icon] of Object.entries(binaryIcons)) {
    const buffer = await download(icon.url);
    fs.writeFileSync(path.join(outputDirectory, `${id}.${icon.extension}`), buffer);
    saved += 1;
    process.stdout.write(`saved ${id}.${icon.extension}\n`);
  }
  process.stdout.write(`completed: ${saved} saved, ${skipped} unavailable\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.stack || error.message}\n`);
  process.exitCode = 1;
});
